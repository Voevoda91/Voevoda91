def parse_karta(path):
    txt = open(path, encoding='utf-8').read()
    body = txt.split('## РАЗДЕЛ Б.')[1].split('## Сводка по карте')[0]
    positions = []
    cur = None
    for line in body.split('\n'):
        m = re.match(r'^### (\d+)\. (.+?) \((\d+) чел\.\)\s*$', line)
        if m:
            cur = dict(n=int(m.group(1)), name=m.group(2), cnt=int(m.group(3)), rows=[])
            positions.append(cur)
            continue
        if cur and line.startswith('| '):
            c = cells(line)
            if len(c) < 9:
                continue
            if c[0] == '№' or set(c[0]) <= {'-'}:
                continue
            if re.match(r'^А\d+$', c[0]):
                continue
            cur['rows'].append(dict(num=c[0], op=c[1], fac=c[2], cons=c[3],
                                    v=int(c[4]), t=int(c[5]), m=c[7], res=num(c[8])))
    return positions


def parse_vedomost(path):
    """Подразделение и отметка о работах повышенной опасности по должности."""
    out = {}
    for line in open(path, encoding='utf-8'):
        if not line.startswith('| '):
            continue
        c = cells(line)
        if len(c) not in (9, 10) or c[0] == '№' or set(c[0]) <= {'-'}:
            continue
        out[c[1]] = dict(subdiv=c[2], rpo=c[-2])
    return out


def parse_perechen(path):
    return open(path, encoding='utf-8').read().split('\n')


def parse_plan(path):
    txt = open(path, encoding='utf-8').read()
    head = txt.split('## БЛОК 1.')[0]
    tail = ''
    m = re.search(r'\n---\n\n## Финансирование', txt)
    if m:
        tail = txt[m.start():]
    # отсекаем старое заключительное примечание — оно пересобирается заново
    tail = re.sub(r'\n---\n\n\*\*Примечание\.\*\*.*$', '', tail, flags=re.S)
    themes = []
    block = None
    for line in txt.split('\n'):
        if line.startswith('## БЛОК'):
            block = 'П1' if 'П1' in line else ('П2' if 'П2' in line else 'П3')
            continue
        if block and line.startswith('| '):
            c = cells(line)
            if len(c) != 10 or c[0] == '№' or set(c[0]) <= {'-'}:
                continue
            themes.append(dict(block=block,
                               title=re.sub(r'\s*—\s*УР\s*\d+\s*\(.*\)?\s*$', '',
                                            re.sub(r'\s*\(УР \d+\)\s*$', '', c[1])),
                               prof=c[2], мер=c[3], иер=c[4], отв=c[5], срок=c[6],
                               показ=c[8], res=num(c[9])))
    return head, themes, tail


