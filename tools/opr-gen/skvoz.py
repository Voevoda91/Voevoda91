# ------------------------------------------------------------------ helpers
def cats_of(pos):
    return [c for c, members in CATS.items() if pos in members]


def residual(code, v, t):
    """Остаточный риск сквозной опасности для конкретных В и Т.

    Пропорционален базовому остатку раздела А и не превышает его.
    """
    _, _, _, bv, bt, bres = A[code]
    val = bres * v * t / (bv * bt)
    return max(1, min(bres, int(round(val))))


def _split_items(text):
    """Разбивает перечень по запятым вне круглых скобок."""
    out, buf, depth = [], [], 0
    for ch in text:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth = max(0, depth - 1)
        if ch == ',' and depth == 0:
            out.append(''.join(buf))
            buf = []
        else:
            buf.append(ch)
    out.append(''.join(buf))
    return [x.strip() for x in out if x.strip()]


def measures_for(code, pos):
    """Базовые меры + адаптированные под должность, без повторов."""
    parts = [BASE_MEASURES[code]]
    for cat in cats_of(pos):
        extra = ADD.get(code, {}).get(cat)
        if extra:
            parts.append(extra)
    seen, out = set(), []
    for chunk in '; '.join(parts).split(';'):
        chunk = chunk.strip()
        if not chunk:
            continue
        key = ' '.join(chunk.split()).strip(' .,;').lower()
        if key in seen:
            continue
        seen.add(key)
        m = re.match(r'^\[[^\]]+\]\s*', chunk)
        tag = m.group(0) if m else ''
        body = chunk[len(tag):]
        # убираем элементы, уже перечисленные в предыдущих пунктах
        items, kept = _split_items(body), []
        for x in items:
            core = re.sub(r'^\[[^\]]+\]\s*', '', x.strip()).strip(' .,;')
            if not core:
                continue
            if ' '.join(core.split()).lower() in seen:
                continue
            seen.add(' '.join(core.split()).lower())
            kept.append(x.strip(' .,;'))
        if not kept:
            continue
        out.append(tag + ', '.join(kept))
    return '; '.join(out)


def applicable(pos):
    """Список сквозных опасностей, применимых к рабочему месту должности.

    Формат записи совпадает с записями профессиональных опасностей:
    (номер, опасность, фактор, последствия, В, Т, меры, остаточный риск).
    """
    ov = OVERRIDE.get(pos, {})
    out = []
    for code in sorted(A, key=lambda k: int(k[1:])):
        vt = ov.get(code, BASE.get(code))
        if vt is None:
            continue
        v, t = vt
        op, fac, cons, _, _, _ = A[code]
        out.append((code, op, fac, cons, v, t, measures_for(code, pos),
                    residual(code, v, t)))
    return out


def skvoznye_rows():
    """Строки справочного раздела А (базовые баллы и меры)."""
    out = []
    for code in sorted(A, key=lambda k: int(k[1:])):
        op, fac, cons, v, t, res = A[code]
        out.append((code, op, fac, cons, v, t, BASE_MEASURES[code], res))
    return out
