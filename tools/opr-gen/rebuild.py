# ------------------------------------------------------------------ helpers
def lvl(ur):
    if ur <= 3:
        return 'низкий'
    if ur <= 7:
        return 'средний'
    if ur <= 12:
        return 'высокий'
    return 'критический'


def fmt(ur, bold_high=True):
    l = lvl(ur)
    if bold_high and l in ('высокий', 'критический'):
        return '%d — **%s**' % (ur, l)
    return '%d — %s' % (ur, l)


def prio(ur):
    return 'П1' if lvl(ur) in ('высокий', 'критический') else ('П2' if lvl(ur) == 'средний' else 'П3')


def plural(n, forms):
    n = abs(int(n)) % 100
    n1 = n % 10
    if 11 <= n <= 14:
        return forms[2]
    if n1 == 1:
        return forms[0]
    if n1 in (2, 3, 4):
        return forms[1]
    return forms[2]


def cells(line):
    parts = re.split(r'(?<!\\)\|', line)
    return [p.strip() for p in parts[1:-1]]


def cell(t):
    return t.replace('|', '\\|').replace('\n', ' ')


def num(s):
    m = re.search(r'(\d+)', s.replace('**', ''))
    return int(m.group(1)) if m else 0


def has_kw(text, kws):
    low = text.lower()
    return any(k in low for k in kws)


